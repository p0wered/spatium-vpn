/**
 * Шейдер светового ядра кнопки подключения
 * Вынесен из компонента отдельно: GLSL длиннее самой обвязки,
 * вперемешку с JSX его невозможно читать.
 *
 * Принцип — «цвет живёт в свете»: никакого акцентного цвета, только белое
 * ядро с холодным спадом. Холод берётся не подмешиванием синего в белое,
 * а дисперсией: три канала считаются на слегка разных радиусах, красный
 * гаснет раньше синего. Физика стекла, а не покраска.
 */

export const coreVert = `
attribute vec2 position;
attribute vec2 uv;
varying vec2 vUv;
void main() {
  vUv = uv;
  gl_Position = vec4(position, 0.0, 1.0);
}`

export const coreFrag = `precision highp float;

uniform vec2  uResolution;
/** Радиус диска кнопки в тех же единицах, что uResolution — единица длины */
uniform float uUnit;
uniform float uTime;
uniform float uOn;    // 0 — отключено, 1 — подключено (плавно едет между)
uniform float uBusy;  // 0..1 — разгон турбулентности на переходных фазах
uniform float uWave;  // 0..1 — прогресс ударной волны, вне (0,1) волны нет
uniform vec3  uIce;
uniform vec3  uBeam;

varying vec2 vUv;

float hash(vec2 p) {
  return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453123);
}

float noise(vec2 p) {
  vec2 i = floor(p);
  vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(
    mix(hash(i + vec2(0.0, 0.0)), hash(i + vec2(1.0, 0.0)), u.x),
    mix(hash(i + vec2(0.0, 1.0)), hash(i + vec2(1.0, 1.0)), u.x),
    u.y
  );
}

float fbm(vec2 p) {
  float v = 0.0;
  float a = 0.5;
  for (int i = 0; i < 4; i++) {
    v += a * noise(p);
    p *= 2.02;
    a *= 0.5;
  }
  return v;
}

/*
 * Тело ядра. Профиль тот же обратноквадратичный, что у фронта волны, — и это
 * главное, что подтягивает свечение к кольцу по достоверности.
 *
 * Была экспонента exp(-(r/R)^1.5 · 2.2): на r = 2R она даёт 0.002, то есть
 * собственный свет ядра умирал сразу за диском, а всё дальше несли отдельно
 * подмешанные ореол, beam и засветка. Отсюда и ощущение стопки градиентов
 * вместо одного источника.
 *
 * Степень 3, а не 2 как у волны. На 1/r² хвост в средней зоне (r = 1…2)
 * оказался настолько тяжёлым, что заливал весь кадр молоком и убивал
 * контраст: центр переставал читаться пересветом. Куб в этой зоне примерно
 * повторяет прежнюю экспоненту, но дальше неё не обрывается — на краю кадра
 * остаётся ~0.02 против 0.002.
 */
float glow(float r, float radius) {
  float g = radius / (max(r, 0.0) + radius * 0.55);
  return g * g * g;
}

/*
 * Профиль фронта ударной волны: d — расстояние до фронта (положительное
 * снаружи), w — толщина. Вынесен в функцию, потому что вызывается трижды —
 * по разу на канал, см. дисперсию в месте вызова.
 *
 * outK/inK — крутизна спада наружу и внутрь. Пока фронт живой, наружу он
 * режется в 2.5 раза круче: у симметричного профиля нет направления, и он
 * читается как линия, которую двигают. К концу волны их сводят почти в
 * равные — фронт теряет направление и расплывается (см. dissolve).
 *
 * Форма обратноквадратичная (приём из Strands), а не гауссова: плотный
 * сердечник и хвост ~1/d². Гаусс при этой ширине и даёт «размытую линию».
 */
float shockProfile(float d, float w, float outK, float inK) {
  float de = d > 0.0 ? d * outK : -d * inK;
  float g = w / (de + w * 0.45);
  return g * g;
}

void main() {
  /*
   * Единица длины — радиус матового диска кнопки: r = 1 ровно на его кромке.
   * Так радиусы в шейдере читаются относительно самой кнопки и не разъезжаются
   * при смене размера канваса (нормализация по короткой стороне этого не давала).
   */
  float t = uTime;
  vec2 pAbs = (vUv * 2.0 - 1.0) * 0.5 * uResolution / uUnit;

  /*
   * Источник смещён от геометрического центра кнопки и медленно дрейфует.
   * Артефакты объектива строятся относительно оптической оси: если источник
   * стоит ровно в центре, засветка и блик вырождаются в концентрические
   * кольца и читаются как обычный радиальный градиент, а не как свет,
   * попавший в камеру. Смещение ~10% радиуса диска — на глаз не замечается
   * как «съехало», но выключает симметрию.
   */
  vec2 src = vec2(-0.06 + 0.09 * sin(t * 0.13), 0.05 + 0.07 * cos(t * 0.11));
  vec2 p = pAbs - src;
  float r = length(p);
  float ang = atan(p.y, p.x);

  /*
   * Дыхание. Выключенным — медленное и глубокое (ядро «спит»), подключённым —
   * частое и мелкое: живое, но не дёргается под таймером сессии.
   */
  float breathe = mix(
    0.86 + 0.14 * sin(t * 0.55),
    0.97 + 0.03 * sin(t * 1.15),
    uOn
  );

  /*
   * Домен-варп радиуса: fbm даёт неровность кромки, угловой шум — медленные
   * протуберанцы внутри ядра. На переходных фазах оба усиливаются (uBusy).
   */
  float turb  = fbm(p * 1.27 + vec2(t * 0.14, -t * 0.11)) - 0.5;

  /*
   * Угловой шум сэмплируется ПО ОКРУЖНОСТИ (cos/sin), а не от самого ang.
   * atan даёт скачок с −π на +π, и шум вида fbm(vec2(ang * k, …)) в этой точке
   * рвётся: на ядре разрыв прятался за радиальной симметрией, а нити кольца
   * проявили его прямой ступенькой на девять часов. Радиус входит масштабом
   * окружности — так остаётся радиальная изменчивость, но период сохраняется.
   */
  vec2 ac = vec2(cos(ang), sin(ang));
  float swirl = fbm(ac * (1.6 + r * 0.9) - vec2(t * 0.18)) - 0.5;
  float rw = max(r + (turb * 0.9 + swirl * 0.6) * (0.058 + 0.092 * uBusy + 0.029 * uOn), 0.0);

  /*
   * Отдельная волнистость для внешних слоёв. У ядра кромка должна оставаться
   * плотной, поэтому модуляция включается только с расстоянием (smoothstep):
   * ближе к центру её нет, дальше внешняя граница свечения гуляет и перестаёт
   * идти строго по окружности. Шум — снова по окружности, чтобы не было шва.
   */
  float lobes = fbm(ac * 1.3 - vec2(t * 0.09)) - 0.5;
  float rHalo = rw * (1.0 - lobes * 0.38 * smoothstep(0.25, 1.3, r));

  /*
   * Анизотропия дальнего света: вбок он уходит примерно в 1.7 раза дальше,
   * чем вверх-вниз, и линии равной яркости становятся линзой, а не
   * окружностью. Ровный круг вокруг кнопки читается нарисованным ореолом;
   * вытянутая по горизонтали форма — тем, что бывает с ярким источником в
   * оптике (та же ось, что у анаморфного блика ниже).
   *
   * Коэффициент считается как отношение анизотропного радиуса к обычному, а
   * потом им домножаются уже готовые радиусы слоёв: так сохраняется весь
   * домен-варп, который эти радиусы к этому моменту накопили.
   */
  float aniso = length(vec2(p.x * 0.58, p.y)) / max(r, 0.0001);

  /*
   * Ядро заметно ШИРЕ диска (r = 1 — его кромка). Иначе весь свет остаётся под
   * матовым стеклом, наружу не выходит ничего, и кнопка читается как
   * металлический шар, а не как источник света.
   */
  /*
   * Отдача от нажатия. Ядро на первых ~15% волны сжимается и тут же
   * отпускает: без этого волна живёт отдельным слоем поверх картинки — её
   * как будто подрисовали, а не выбросило ядро. Спад экспоненциальный и
   * быстрый (≈130 мс из 850): это удар, а не вторая анимация.
   */
  float kick = (uWave > 0.0001 && uWave < 1.0) ? exp(-uWave * 14.0) : 0.0;

  float radius = mix(0.45, 0.86, uOn) * breathe * (1.0 - kick * 0.16);

  /*
   * Дисперсия: красный канал считается на большем радиусе (гаснет раньше),
   * синий — на меньшем (уходит дальше). В центре все три в единице — белое
   * ядро; к краю остаётся холодный спад.
   */
  float d = 0.052 * mix(0.6, 1.0, uOn);
  vec3 col = vec3(
    glow(rw + d, radius),
    glow(rw,     radius),
    glow(rw - d, radius)
  ) * 0.166;  // 1/glow(0): тело ядра, как и раньше, приходит в центр единицей

  /* Раскалённый центр — выбитый в белое, источник всего света. Подключённым
     поднят против прежних 1.15: компрессия ниже больше не срезает пик
     клампом, она к нему плавно подходит, и на старом значении центр
     не доходил до белого */
  col += vec3(exp(-pow(rw / (radius * 0.42), 2.0)) * mix(0.35, 1.35, uOn));

  /*
   * Холодный ореол и глубокий синий в дальнем спаде — beam только здесь.
   * Ослаблены против прежних значений: у тела ядра теперь свой длинный хвост
   * 1/r², и на старых амплитудах эти два слоя складывались с ним в туман.
   */
  /*
   * Радиусы слоёв заметно ужаты против прежних. Это не «стало меньше света»:
   * раньше их душило гашение кромок, начинавшееся уже на кромке диска, и
   * реальный размер ореола задавала маска, а не сами числа. Когда маску
   * отодвинули, выяснилось, сколько эти слои светят на самом деле — весь кадр
   * заливало ровным серым. Теперь форму держит сам спад: примерно 1.5 единицы
   * по вертикали до внятной границы и почти чернота к 2.5.
   */
  float rHaloA = rHalo * aniso;
  col += uIce  * exp(-pow(rHaloA / (radius * 1.4), 2.0)) * (0.04 + 0.20 * uOn);
  col += uBeam * exp(-rHaloA * 1.60) * (0.07 + 0.13 * uOn);

  /*
   * Паразитная засветка объектива (veiling glare) — то, из-за чего свет
   * фонарика, попавший в камеру, заливает весь кадр. Заменяет прежнюю ровную
   * широкую засветку.
   *
   * Ключевое здесь — НЕОДНОРОДНОСТЬ: ровный радиальный градиент глаз читает
   * как градиент. Настоящее рассеяние идёт на микродефектах стекла и даёт
   * мягкие нерегулярные лучи, поэтому засветка промодулирована угловым шумом.
   * Спад степени 1.35 вместо гауссова — заметно длиннее хвост, свет доходит
   * до краёв кадра, как и положено паразитному.
   */
  /*
   * Две угловые модуляции с разным масштабом:
   *   tongues — крупные медленно перетекающие «языки» засветки. Это они
   *     снимают ощущение ровной окружности; модулируют РАДИУС, а не яркость,
   *     иначе у такого пологого хвоста изменение незаметно.
   *   rays — мелкая нерегулярная структура лучей от микродефектов стекла.
   */
  float tongues = fbm(ac * 1.5 - vec2(t * 0.12)) - 0.5;
  float rays = 0.65 + 0.35 * fbm(ac * 4.0 + vec2(t * 0.05));
  float glareR = rHaloA * (1.0 - tongues * 0.75);
  col += mix(uIce, vec3(1.0), 0.35) * exp(-pow(glareR / 2.2, 1.35)) * rays * (0.012 + 0.035 * uOn);

  /*
   * Анаморфный блик — намеренно на пределе различимости (пользователь просил
   * «еле заметный»): горизонтальная полоса через источник. Затухание по
   * вертикали гауссово и узкое, по горизонтали экспоненциальное и длинное —
   * так полоса остаётся тонкой, но уходит далеко в стороны.
   */
  float streak = exp(-pow(p.y / 0.11, 2.0)) * exp(-abs(p.x) * 0.85);
  col += mix(uIce, vec3(1.0), 0.55) * streak * (0.015 + 0.075 * uOn);

  /*
   * Выключенное ядро едва тлеет. На переходных фазах приподнимаем яркость:
   * иначе «connecting» отличается от «off» только бегущей дугой, и кадр
   * не читается как разгон.
   */
  col *= mix(mix(0.35, 0.62, uBusy), 1.0, uOn);

  /*
   * Тональная компрессия — второй приём, взятый у волны (и у Strands).
   * Слои выше складывались линейно, и сумма в центре уходила далеко за
   * единицу: всё, что ярче, срезалось клампом в плоское белое пятно с жёсткой
   * кромкой, а переход в ореол получался линейным — глаз читает такое как
   * градиент, а не как пересвет.
   *
   * После 1 - exp(-x) сердечник плавно доходит до чистого белого, срезать
   * нечего, а в спаде остаётся то, что развела дисперсия. Ставится после
   * множителя состояния: тусклое ядро — это меньше света на входе, и
   * компрессия обязана это видеть, иначе выключенное состояние пережимается
   * так же, как подключённое.
   *
   * Усиление 1.35 — не декоративное число: на единице кривая ощутимо
   * подбирает нижний диапазон (0.5 → 0.39), а выключенное ядро целиком в нём
   * и живёт, и оно заметно тускнело. На 1.35 тусклые состояния остаются на
   * прежней яркости, а подключённый центр уходит в белое — 0.98 на выходе
   * против 2.85 на входе.
   */
  col = 1.0 - exp(-col * 1.35);

  /*
   * Гашение кромок канваса (PROJECT.md → «Правило кромок»): широкая засветка
   * иначе доходит до краёв прямоугольника и обрывается прямой линией — на
   * чёрном фоне этот стык читается как шов под шапкой.
   *
   * Маска эллиптическая, по форме канваса, а не квадратная: у квадратной
   * (max по осям) спад повторяет прямоугольник и вокруг кнопки становится
   * виден светлый прямоугольник с мягкими углами. Эллипс обнуляет свет на
   * серединах кромок.
   *
   * Начало сдвинуто с 0.45 к 0.75. На 0.45 маска принималась душить свет уже
   * на кромке диска: размер и форму ореола задавала она, а не спад света, и
   * никакого «плавно уходящего в темноту» свечения не могло быть в принципе.
   * Теперь маска — только страховка у самой кромки канваса, а канвас вдобавок
   * шире экрана (CANVAS_OVERHANG), поэтому по горизонтали она работает вообще
   * за пределами кадра.
   */
  col *= 1.0 - smoothstep(0.75, 1.0, length(vUv * 2.0 - 1.0));

  /*
   * Ударная волна. Складывается ПОСЛЕ множителя состояния — это событие, а не
   * состояние: до множителя вспышка от нажатия гасла ровно там, где должна
   * быть ярче всего, потому что ядро в этот момент ещё не разгорелось.
   *
   * И ПОСЛЕ гашения кромок. Маска начинает давить с r ≈ 0.98 единицы, а
   * матовый диск кнопки заканчивается ровно на r = 1.0 — то есть полосы, где
   * волна одновременно вышла из-под стекла и ещё не задавлена, не существует
   * в принципе. Раньше волна жила именно в этом зазоре и потому читалась
   * бледной. Правило кромок при этом не нарушено: маска нужна тому свету,
   * который уходит в бесконечность, а волна ограничена сама — её радиус
   * не доходит до края канваса (1.8 против 2.18; запас нужен под разбухший
   * к концу фронт), и обрываться прямой линией ей нечем.
   */
  if (uWave > 0.0001 && uWave < 1.0) {
    /* От геометрического центра кнопки, а не от смещённого источника: волну
       порождает нажатие, а не свет — она обязана расходиться из-под пальца */
    float rAbs = length(pAbs);

    /*
     * Радиус с сильным замедлением (pow 0.45), а не линейный. Линейное
     * движение глаз читает как анимацию, а не как выброс; и всё до r = 1
     * закрыто диском, где волну всё равно размывает backdrop-blur. С таким
     * замедлением кольцо выскакивает из-под стекла к 24% прогресса вместо
     * 37% — почти вся жизнь эффекта проходит на виду.
     */
    float wr = pow(uWave, 0.45) * 1.8;

    /*
     * Размытие фронта на последней трети. Волна не обязана исчезать, оставаясь
     * до конца тем же чётким кольцом, — это читается как «выключили слой».
     * К концу фронт расплывается: толстеет и теряет направленность (оба
     * параметра ниже едут этим множителем).
     *
     * Именно размытие, а не распад: пробовали рвать кольцо угловым шумом на
     * клочья — эффектно, но выглядит самостоятельной анимацией поверх экрана,
     * а не откликом кнопки.
     */
    float dissolve = smoothstep(0.35, 1.0, uWave);

    /*
     * Слом идеальной окружности. Весь остальной шейдер намеренно ломает
     * симметрию — смещённый источник, домен-варп, языки засветки, — и волна
     * была единственным объектом кадра, идущим ровным циркульным кругом;
     * именно это и выдавало в ней нарисованность. Шум берётся по окружности
     * (нормаль от центра кнопки), поэтому шва на девять часов нет, а лёгкий
     * дрейф по uWave не даёт оболочке выглядеть жёстко отштампованной.
     *
     * Амплитуда постоянная и малая. Разгонять её к концу пробовали — вместе с
     * подмешанной второй октавой контур превращался в шевелящуюся шестерёнку:
     * это уже не размытие, а деформация, и волна начинала читаться отдельно
     * наложенным эффектом, а не частью интерфейса.
     */
    vec2 acw = rAbs > 0.0001 ? pAbs / rAbs : vec2(1.0, 0.0);
    float wobble = fbm(acw * 1.15 + vec2(uWave * 0.6)) - 0.5;
    wr *= 1.0 + wobble * 0.1;

    /*
     * Огибающая яркости. Раньше был монотонный спад от старта: пик приходился
     * на момент, когда кольцо ещё под стеклом. Теперь разгон привязан к
     * РАДИУСУ (emerge), а смерть — к прогрессу (гарантированный ноль на
     * uWave = 1): максимум встаёт сразу за кромкой диска. Радиус здесь уже
     * промодулирован, поэтому и проступает волна по кругу неравномерно.
     *
     * Степень 1.4, а не 1.7: на более крутом спаде волна гасла раньше, чем
     * успевала распуститься, и роспуска просто не было видно.
     */
    float amp = smoothstep(0.7, 1.2, wr) * pow(1.0 - uWave, 1.4);

    float d = rAbs - wr;

    /* Толщина растёт и с радиусом (расходящееся возмущение расплывается), и с
       роспуском — к концу фронт размазывается ещё втрое */
    float w = (0.045 + 0.045 * wr) * (1.0 + 2.0 * dissolve);

    /* Направленность фронта уходит вместе с когерентностью: к концу спады
       наружу и внутрь почти равны, и кольцо перестаёт «лететь» */
    float outK = mix(4.0, 1.3, dissolve);
    float inK = mix(1.6, 1.05, dissolve);

    /*
     * Дисперсия вместо покраски — тот же приём, на котором построено ядро
     * (PROJECT.md → «цвет живёт в свете»). Раньше волна была залита
     * mix(uIce, white): то есть именно покрашена, ровно то, что в проекте
     * запрещено.
     *
     * Каналы расходятся двумя способами сразу: синий идёт чуть ВПЕРЕДИ фронта
     * и по более широкому профилю, красный отстаёт и режется уже — передний
     * край получается холодным, шлейф за фронтом тёплым, а на самом пике все
     * три сходятся в белое. Расхождение растёт с радиусом: чем дальше ушла
     * оболочка, тем сильнее разъезжаются каналы.
     */
    float lead = 0.004 * wr;
    vec3 g = vec3(
      shockProfile(d + lead, w * 0.94, outK, inK),
      shockProfile(d,        w,        outK, inK),
      shockProfile(d - lead, w * 1.08, outK, inK)
    );

    /*
     * Тональная компрессия — приём из Strands. Складывать линейно нельзя:
     * сумма упирается в кламп альфы уже серой, и фронт никогда не выбивает.
     * После 1 - exp(-x) сердечник уходит в чистый белый, а по краям остаётся
     * то, что развела дисперсия — свет, а не краска.
     */
    col += 1.0 - exp(-g * amp * 1.8);

    /*
     * Вспышка отдачи в самом центре кнопки. Стоит под матовым стеклом, и это
     * намеренно: backdrop-blur размажет её в короткое цветение под диском —
     * видно, что волну выбросило изнутри.
     */
    col += mix(uIce, vec3(1.0), 0.7) * kick * exp(-pow(rAbs / 0.55, 2.0)) * 0.55;
  }

  /*
   * col уже и есть вклад света, сложенный из слагаемых, — это готовый
   * премультиплицированный цвет. Домножать его на альфу ещё раз (как делают
   * фоны, где col — цвет, а a — покрытие) нельзя: спад гаснет квадратично,
   * и весь ореол за кромкой диска уходит в чёрный.
   */
  float a = clamp(max(max(col.r, col.g), col.b), 0.0, 1.0);
  gl_FragColor = vec4(col, a);
}`
